"""Generate directly loadable native Component sources; no dynamic class factories.

Usage:
    python materials-quality/scripts/build_science_components.py
    python materials-quality/scripts/build_science_components.py --check

``--check`` regenerates into a temporary directory and compares byte-for-byte
with the checked-in components and catalog, exiting non-zero on drift.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from importlib import import_module
from pathlib import Path

from materials_quality.science.categories import category_label
from materials_quality.science.ui_schema import (
    FEATURE_OPERATIONS,
    REPORT_COLLECTION_KEYS,
    contract_for,
    fields_for,
)

ROOT = Path(__file__).resolve().parents[1]
GENERATED_HEADER = "# Generated by scripts.build_science_components."
MODULES = [
    "io_nodes",
    "extract_nodes",
    "preprocessing",
    "materials",
    "statistics",
    "visualization",
    "literature",
    "method_cards",
    "chemometrics",
    "result_evidence",
    "research_plan",
]


def build(root: Path) -> list[dict]:
    entries = []
    for module in MODULES:
        for item in import_module(f"materials_quality.science.{module}").CATALOG:
            item = dict(item)
            prefix, _suffix = item["key"].split(".")
            directory = (
                "materials_"
                + {
                    "io": "sources",
                    "extract": "extraction",
                    "preprocess": "preprocessing",
                    "materials": "analysis",
                    "stats": "statistics",
                    "viz": "visualization",
                    "export": "visualization",
                    "lit": "literature",
                }[prefix]
            )
            class_name = "Science" + "".join(p.title() for p in item["key"].replace(".", "_").split("_"))
            filename = item["key"].replace(".", "_")
            item.update(directory=directory, filename=filename, class_name=class_name)
            item["category_label"] = category_label(item["category"])
            item.update(contract_for(item["key"]))
            item["context_input"] = not item["data_input"] and (item["table_input"] or item["tables_input"])
            item["reports_input"] = item["key"] in REPORT_COLLECTION_KEYS or item["artifacts_output"]
            item["ui_version"] = 2
            item["features_output"] = item["key"] in FEATURE_OPERATIONS
            item["form_fields"] = fields_for(item["key"])
            entries.append(item)
            code = f"""{GENERATED_HEADER}
# Edit the shared adapter or catalog instead.
from lfx.custom import Component
from lfx.schema import Data, DataFrame, Message

from materials_quality.science.canvas_adapter import (
    node_inputs,
    node_outputs,
    output_artifacts,
    output_features,
    output_report,
    output_summary,
    output_table,
)
from materials_quality.science.ui_schema import ScienceFormMixin, refresh_config


class {class_name}(ScienceFormMixin, Component):
    display_name = {("材料科学·" + item["title"])!r}
    description = {("可追溯的" + item["title"] + "；具体方法与前提见随仓库提供的手册。")!r}
    name = {class_name!r}
    icon = {contract_for(item["key"])["icon"]!r}
    ui_contract_version = 2
    ui_operation_key = {item["key"]!r}
    inputs = node_inputs({item["key"]!r}, {item["default_config"]!r})
    outputs = node_outputs({item["key"]!r})

    def update_build_config(self, build_config, field_value, field_name=None):
        return refresh_config(self, {item["key"]!r}, build_config, field_value, field_name)

    def build_table(self) -> DataFrame:
        return output_table(self, {item["key"]!r})

    def build_report(self) -> Data:
        return output_report(self, {item["key"]!r})

    def build_features(self) -> DataFrame:
        return output_features(self, {item["key"]!r})

    def build_artifacts(self) -> DataFrame:
        return output_artifacts(self, {item["key"]!r})

    def build_summary(self) -> Message:
        return output_summary(self, {item["key"]!r})
"""
            dest = root / "components" / directory
            dest.mkdir(parents=True, exist_ok=True)
            (dest / (filename + ".py")).write_text(code, encoding="utf-8", newline="\n")
    catalog_path = root / "src" / "materials_quality" / "science" / "catalog.json"
    catalog_path.parent.mkdir(parents=True, exist_ok=True)
    catalog_path.write_text(json.dumps(entries, ensure_ascii=False, indent=2), encoding="utf-8", newline="\n")
    paths = [str(root / "components" / e["directory"] / (e["filename"] + ".py")) for e in entries]
    subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--config", str(ROOT / "pyproject.toml"), *paths],
        check=True,
        capture_output=True,
    )
    return entries


def check() -> int:
    with tempfile.TemporaryDirectory() as temp:
        temp_root = Path(temp)
        entries = build(temp_root)
        problems: list[str] = []
        expected: set[Path] = set()
        for entry in entries:
            rel = Path("components") / entry["directory"] / (entry["filename"] + ".py")
            expected.add(rel)
            fresh = temp_root / rel
            current = ROOT / rel
            if not current.is_file():
                problems.append(f"missing: {rel.as_posix()}")
            elif current.read_bytes() != fresh.read_bytes():
                problems.append(f"drift: {rel.as_posix()}")
        catalog_rel = Path("src/materials_quality/science/catalog.json")
        if (ROOT / catalog_rel).read_bytes() != (temp_root / catalog_rel).read_bytes():
            problems.append(f"drift: {catalog_rel.as_posix()}")
        for path in (ROOT / "components").rglob("*.py"):
            try:
                first = path.read_text(encoding="utf-8").splitlines()[:1]
            except OSError:
                continue
            if first and first[0].startswith(GENERATED_HEADER):
                rel = path.relative_to(ROOT)
                if rel not in expected:
                    problems.append(f"stale: {rel.as_posix()}")
        if problems:
            print("Science component drift detected:")
            for problem in problems:
                print(" -", problem)
            return 1
        print(f"Science components up to date ({len(entries)} generated).")
        return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on generated-file drift")
    args = parser.parse_args(argv)
    if args.check:
        return check()
    entries = build(ROOT)
    print(f"Generated {len(entries)} native components")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
