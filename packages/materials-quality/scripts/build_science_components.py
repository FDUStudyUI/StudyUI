"""Generate directly loadable native Component sources; no dynamic class factories."""

import json
import subprocess
import sys
from importlib import import_module
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = [
    "io_nodes",
    "extract_nodes",
    "preprocessing",
    "materials",
    "statistics",
    "visualization",
    "literature",
]


def main():
    entries = []
    for module in MODULES:
        for item in import_module(f"materials_quality.science.{module}").CATALOG:
            item = dict(item)
            prefix, suffix = item["key"].split(".")
            directory = (
                "materials_"
                + {
                    "io": "sources",
                    "extract": "extraction",
                    "preprocess": "preprocessing",
                    "materials": "analysis",
                    "stats": "statistics",
                    "viz": "visualization",
                    "export": "visualization",
                    "lit": "literature",
                }[prefix]
            )
            class_name = "Science" + "".join(p.title() for p in item["key"].replace(".", "_").split("_"))
            filename = item["key"].replace(".", "_")
            item.update(directory=directory, filename=filename, class_name=class_name)
            entries.append(item)
            code = f"""# Generated by scripts.build_science_components.
# Edit the shared adapter or catalog instead.
from lfx.custom import Component
from lfx.schema import Data, DataFrame, Message

from materials_quality.science.langflow_adapter import (
    node_inputs,
    node_outputs,
    output_artifacts,
    output_report,
    output_summary,
    output_table,
)


class {class_name}(Component):
    display_name = {("材料科学·" + item["title"])!r}
    description = {("可追溯的" + item["title"] + "；具体方法与前提见随仓库提供的手册。")!r}
    name = {class_name!r}
    icon = 'FlaskConical'
    inputs = node_inputs({item["default_config"]!r})
    outputs = node_outputs()

    def build_table(self) -> DataFrame:
        return output_table(self, {item["key"]!r})

    def build_report(self) -> Data:
        return output_report(self, {item["key"]!r})

    def build_artifacts(self) -> DataFrame:
        return output_artifacts(self, {item["key"]!r})

    def build_summary(self) -> Message:
        return output_summary(self, {item["key"]!r})
"""
            dest = ROOT / "components" / directory
            dest.mkdir(exist_ok=True)
            (dest / (filename + ".py")).write_text(code, encoding="utf-8", newline="\n")
    (ROOT / "src/materials_quality/science/catalog.json").write_text(
        json.dumps(entries, ensure_ascii=False, indent=2), encoding="utf-8", newline="\n"
    )
    paths = [str(ROOT / "components" / e["directory"] / (e["filename"] + ".py")) for e in entries]
    subprocess.run([sys.executable, "-m", "ruff", "format", *paths], check=True)
    print(f"Generated {len(entries)} native components")


if __name__ == "__main__":
    main()
